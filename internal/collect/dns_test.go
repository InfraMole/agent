package collect

import (
	"reflect"
	"strings"
	"testing"
)

func TestParseResolvConf(t *testing.T) {
	conf := `# Generated by NetworkManager
search corp.local
nameserver 10.0.0.53
; comment
nameserver   10.0.0.54
options edns0
nameserver
`
	got := parseResolvConf(strings.NewReader(conf))
	if want := []string{"10.0.0.53", "10.0.0.54"}; !reflect.DeepEqual(got, want) {
		t.Fatalf("got %v, want %v", got, want)
	}
}

func TestUsableResolvers(t *testing.T) {
	got := usableResolvers([]string{
		"127.0.0.53",               // systemd-resolved stub
		"10.0.0.53",                // kept
		"10.0.0.53",                // duplicate
		"::1",                      // loopback
		"fe80::1%eth0",             // link-local
		"fec0:0:0:ffff::1",         // Windows site-local default
		"::ffff:192.168.1.1",       // mapped → IPv4
		"2001:db8::53",             // kept
		"not-an-ip", "0.0.0.0", "", // junk
	})
	if want := []string{"10.0.0.53", "192.168.1.1", "2001:db8::53"}; !reflect.DeepEqual(got, want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	many := make([]string, 0, 12)
	for i := 1; i <= 12; i++ {
		many = append(many, "10.0.1."+itoa(uint32(i)))
	}
	if n := len(usableResolvers(many)); n != MaxDNSServers {
		t.Fatalf("want at most %d, got %d", MaxDNSServers, n)
	}
}

func TestDNSServersOnThisHost(t *testing.T) {
	servers, found, err := DNSServers(t.Context())
	if err != nil {
		t.Fatalf("DNSServers: %v", err)
	}
	t.Logf("found=%v servers=%v", found, servers)
	if len(servers) > MaxDNSServers {
		t.Fatalf("too many: %v", servers)
	}
}
